import express from 'express';
import { getAllOrders, getAllProducts, getAllCustomers, updateOrderStatus, createProductAdmin, updateProductAdmin, deleteProductAdmin, getBestSellers, getAnalytics, getSettings, updateSettings } from '../controllers/adminController.js';
import { getRecipes, createRecipe, updateRecipe, deleteRecipe } from '../controllers/recipeController.js';
import { protect, adminOnly } from '../middleware/authMiddleware.js';
const router = express.Router();
router.use(protect, adminOnly);
router.get('/orders', getAllOrders);
router.get('/products', getAllProducts);
router.get('/customers', getAllCustomers);
router.get('/best-sellers', getBestSellers);
router.get('/analytics', getAnalytics);
router.get('/settings', getSettings);
router.put('/settings', updateSettings);
router.put('/orders/:id/status', updateOrderStatus);
router.post('/products', createProductAdmin);
router.put('/products/:id', updateProductAdmin);
router.delete('/products/:id', deleteProductAdmin);
router.get('/recipes', getRecipes);
router.post('/recipes', createRecipe);
router.put('/recipes/:id', updateRecipe);
router.delete('/recipes/:id', deleteRecipe);
export default router;
